def _cell(f: dict, bold: bool = False) -> str:
    acc = f"{f['accuracy']:.3f}" if f.get("accuracy") is not None else "—"
    acc = f"**{acc}**" if bold else acc
    return f"{acc}<br><sub>{f['correct']}/{f['scored']}</sub>"


def build(lang: str) -> str:
    finals, tx, nm = load_finals(), TEXT[lang], NAMES[lang]
    arms = ["b0", "m0", "m1"]
    lines = [START, "", tx["own"], "", f"| {tx['field']} | B0 | M0 | M1 |", "|---|---:|---:|---:|"]
    for i, key in enumerate(TRADE_FIELDS):
        if i == 0:
            lines.append(f"| *{tx['row']}* | | | |")
        if i == 6:
            lines.append(f"| *{tx['doc']}* | | | |")
        fs = {a: finals[a]["sets"]["trade:test"]["strict"]["fields"][key] for a in arms}
        best = max(fs[a]["accuracy"] or 0 for a in arms)
        lines.append(f"| {nm[key]} | " + " | ".join(_cell(fs[a], (fs[a]["accuracy"] or 0) == best and best > 0) for a in arms) + " |")
    lines += ["", tx["pub"], "", f"| {tx['field']} | B0 IID | M0 IID | M1 IID | B0 OOD | M0 OOD | M1 OOD |",
              "|---|---:|---:|---:|---:|---:|---:|"]
    for key in PUBLIC_FIELDS:
        cells = []
        for st in ("public:iid_final|clean", "public:ood_final|clean"):
            fs = {a: finals[a]["sets"][st]["strict"]["fields"][key] for a in arms}
            best = max(fs[a]["accuracy"] or 0 for a in arms)
            cells += [_cell(fs[a], (fs[a]["accuracy"] or 0) == best and best > 0) for a in arms]
        lines.append(f"| {nm[key]} | " + " | ".join(cells) + " |")
    lines += ["", f"<sub>{tx['note']}</sub>", "", END]
    return "\n".join(lines)


def apply(check: bool = False) -> list[str]:
    bad = []
    for name, lang in (("README.md", "en"), ("README.ko.md", "ko")):
        path = REPO / name
        text = path.read_text(encoding="utf-8")
        if START not in text or END not in text:
            bad.append(f"{name}: markers missing")
            continue
        head, rest = text.split(START, 1)
        _, tail = rest.split(END, 1)
        new = head + build(lang) + tail
        if new != text:
            bad.append(name)
            if not check:
                path.write_text(new, encoding="utf-8", newline="\n")
    return bad


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    changed = apply(a.check)
    print(("differs: " if a.check else "updated: ") + (", ".join(changed) or "none"))
    return 1 if a.check and changed else 0


if __name__ == "__main__":
    sys.exit(main())
